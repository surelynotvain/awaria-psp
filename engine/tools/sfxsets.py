"""Per-scene sound effect sets for VCPE 5.6 sound residency -> <gen>/awsfx.c, awsfx.h.

Each scene keeps only the effects its own objects and the prefabs it can instantiate reference (build/reach.json from
crawl.py + the scene's object data, the same lists awpack.py used to pick the sounds). The sizes come from the
generated g_sfx table, so the sets always match the AW.PAK of that build. AW_SFX_SLAB is the biggest set plus room for
a sound still playing across a switch (a door sound on a persistent Manager voice).
Usage (from port/tools): python3 sfxsets.py [GEN_DIR]   (default ../build/gen; the demo: ../build/demo/gen)"""
import json, os, re, sys

B = "../build"
GEN = sys.argv[1] if len(sys.argv) > 1 else os.path.join(B, "gen")
SLACK = 64 * 1024
ALIGN = 16

src = open(os.path.join(GEN, "awdata.c")).read()
m = re.search(r"const SoundDef g_sfx\[(\d+)\] = \{", src)
body = src[m.end():src.index("};", m.end())]
sfx = [(n, int(sz)) for n, off, sz, ns in re.findall(r'\{"([^"]+)",(\d+),(\d+),(\d+)\}', body)]
assert len(sfx) == int(m.group(1)), "g_sfx parse"
sid = {n: i for i, (n, _) in enumerate(sfx)}
hdr = open(os.path.join(GEN, "awdata.h")).read()
nscenes = int(re.search(r"#define NUM_SCENES (\d+)", hdr).group(1)) if "NUM_SCENES" in hdr else 14
reach = json.load(open(os.path.join(B, "reach.json")))


def refs(v, out):
    if isinstance(v, str) and v.startswith("AudioClip:"):
        out.add(v.split(":", 1)[1])
    elif isinstance(v, dict):
        for x in v.values(): refs(x, out)
    elif isinstance(v, list):
        for x in v: refs(x, out)


nbytes = (len(sfx) + 7) // 8
sets, sizes = [], []
for n in range(nscenes):
    names = set(reach.get(str(n), {}).get("audio", []))
    path = os.path.join(B, "scenes", "level%d.json" % n)
    if os.path.exists(path):
        refs(json.load(open(path))["objects"], names)
    ids = sorted(sid[a] for a in names if a in sid)
    bits = bytearray(nbytes)
    for i in ids:
        bits[i >> 3] |= 1 << (i & 7)
    sets.append(bits)
    sizes.append(sum((sfx[i][1] + ALIGN - 1) // ALIGN * ALIGN for i in ids))
slab = max(sizes) + SLACK
total = sum(sz for _, sz in sfx)
c = ["/* generated by tools/sfxsets.py - do not edit */", '#include "awsfx.h"',
     "const unsigned char g_scene_sfx[%d][%d] = {" % (nscenes, nbytes)]
for n, bits in enumerate(sets):
    c.append("    {%s},   /* scene %d: %d KB */" % (",".join(str(b) for b in bits), n, sizes[n] // 1024))
c.append("};")
c.append("const unsigned g_scene_sfx_bytes[%d] = {%s};" % (nscenes, ", ".join(map(str, sizes))))
h = ["/* generated by tools/sfxsets.py - do not edit */", "#ifndef AWSFX_H", "#define AWSFX_H",
     "#define AW_SFX_SLAB %du   /* biggest scene set %d KB + %d KB; all effects: %d KB */" % (slab, max(sizes) // 1024, SLACK // 1024, total // 1024),
     "#define AW_SFX_SETS %d" % nscenes,
     "extern const unsigned char g_scene_sfx[%d][%d];" % (nscenes, nbytes),
     "extern const unsigned g_scene_sfx_bytes[%d];" % nscenes, "#endif"]
open(os.path.join(GEN, "awsfx.c"), "w").write("\n".join(c) + "\n")
open(os.path.join(GEN, "awsfx.h"), "w").write("\n".join(h) + "\n")
print("sfx sets: %d scenes, biggest %d KB, slab %d KB (all effects %d KB)" % (nscenes, max(sizes) // 1024, slab // 1024, total // 1024))
